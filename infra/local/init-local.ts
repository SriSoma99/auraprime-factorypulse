// Generates infra/local/.env.local from the config schema (ADR-030 item 8).
// Passwords are random per machine and never committed (invariant 7). Re-running keeps existing secrets.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join } from "node:path";
import { loadConfig, findRepoRoot } from "@fp/config";

const root = findRepoRoot(process.cwd());
const cfg = loadConfig({ rootDir: root });
const file = join(root, "infra", "local", ".env.local");
const existing = new Map<string, string>();
if (existsSync(file)) for (const line of readFileSync(file, "utf8").split("\n")) {
  const i = line.indexOf("="); if (i > 0) existing.set(line.slice(0, i), line.slice(i + 1));
}
const secret = (name: string) => existing.get(name) ?? randomBytes(24).toString("base64url");
const vars: Record<string, string> = {
  FP_DB_NAME: cfg.db.name,
  FP_DB_ADMIN_USER: cfg.db.admin_user,
  FP_DB_PORT: String(cfg.db.port),
  [cfg.db.admin_password_secret]: secret(cfg.db.admin_password_secret),
  [cfg.db.app_password_secret]: secret(cfg.db.app_password_secret),
  EXPO_PUBLIC_FP_API_BASE_URL: cfg.app.api_base_url,
};
writeFileSync(file, "# Generated by pnpm local:init. Local secrets: do not commit.\n" +
  Object.entries(vars).map(([k, v]) => `${k}=${v}`).join("\n") + "\n", { mode: 0o600 });
console.log(`wrote ${file}`);
// The Expo app reads EXPO_PUBLIC_* from its own project folder; only non-secret values go here.
const appEnv = join(root, "apps", "app", ".env.local");
writeFileSync(appEnv, `# Generated by pnpm local:init. Not secret.\nEXPO_PUBLIC_FP_API_BASE_URL=${cfg.app.api_base_url}\nEXPO_PUBLIC_FP_POLL_INTERVAL_MS=${cfg.app.poll_interval_ms}\n`);
console.log(`wrote ${appEnv}`);
